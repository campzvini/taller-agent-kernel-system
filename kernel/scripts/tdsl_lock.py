from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# ── § 1 — CONFIG — source of truth and emission targets ──

KERNEL_HOME = Path(__file__).resolve().parent.parent
DEFAULT_KERNEL = KERNEL_HOME / "grammar"
SCHEMA_SUBPATH = "schemas"
SHARED = KERNEL_HOME / "skills/_shared"

# dialects the harness authors; core-types and template are support dialects
AUTHORED = tuple(sorted(p.name.removesuffix(".schema.json") for p in (DEFAULT_KERNEL / SCHEMA_SUBPATH).glob("*.schema.json")))


def emit(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {path}")


# ── § 2 — LOCK — the only place exact schema revisions live ──


def build_lock(schemas: Path) -> list[str]:
    registry = json.loads((schemas / "registry.json").read_text(encoding="utf-8"))
    entries = {e["dialect"]: e for e in registry["entries"]}
    lines = [
        "# GENERATED by ~/.codex/scripts/tdsl_lock.py — do not edit by hand.",
        "# Single source for exact schema revisions. Re-run after any kernel grammar schema change.",
        "",
        "¶ - Single source for exact schema revisions across kernel grammar dialects.",
        "",
        "¶ 1 — Revisions",
        "",
        "schema_lock:",
        "  source @kernel/grammar/schemas/registry.json",
        f"  registry {registry['registry']}",
        "",
        "  revisions:",
    ]
    for dialect in sorted(entries):
        lines.append(f"    {dialect}: {entries[dialect]['schema_revision']}")
    lines += [
        "",
        "  rule copy the revision of the emitted dialect verbatim into the artifact `schema_revision` field",
        "  rule never infer a revision from filename, path, branch, or prose",
        "  repin python ~/.codex/scripts/tdsl_lock.py",
    ]
    return lines


# ── § 3 — CONTRACTS — object child fields and enums the template body cannot show ──


def build_contracts(schemas: Path) -> list[str]:
    core = json.loads((schemas / "core-types@1.schema.json").read_text(encoding="utf-8"))
    types = core["type_definitions"]

    lines = [
        "# GENERATED by ~/.codex/scripts/tdsl_lock.py — do not edit by hand.",
        "# What a template body cannot show: object child fields and enum vocabularies.",
        "# Read this only when authoring an object splice `{#name}` or an enum-valued field.",
        "",
        "¶ - Object field contracts and closed enum vocabularies per dialect.",
        "",
        "¶ 1 — Object contracts",
        "",
        "object_contracts: # `{#name}` in a template body expands to exactly these fields, in this order",
    ]
    for name in sorted(k for k in types if k.startswith("object:")):
        definition = types[name]
        fields = definition.get("fields", {})
        order = list(fields)  # declared order is the JSON insertion order
        lines.append(f"  {name}:")
        for field in order:
            spec = fields[field]
            flag = "" if spec.get("required", False) else " optional"
            kind = spec.get("type", "unknown")
            enum = spec.get("enum")
            if enum:
                kind = "|".join(enum)
            lines.append(f"    {field} {kind}{flag}")
        if definition.get("unknown_fields") == "forbidden":
            lines.append("    # unknown fields forbidden")

    lines += ["", "¶ 2 — Enums", "", "enums: # closed vocabularies per dialect; any other value refuses"]
    for dialect in AUTHORED:
        path = schemas / f"{dialect}.schema.json"
        if not path.is_file():
            continue
        schema = json.loads(path.read_text(encoding="utf-8"))
        collected: list[str] = []
        for field in schema.get("fields", []):
            if field.get("enum"):
                collected.append(f"    {field['name']}: [{' '.join(field['enum'])}]")
        for block in schema.get("accumulated_blocks", []):
            for field in block.get("fields", []):
                if field.get("enum"):
                    collected.append(
                        f"    {block['key']}.{field['name']}: [{' '.join(field['enum'])}]"
                    )
        if collected:
            lines.append(f"  {dialect}:")
            lines.extend(sorted(set(collected)))

    lines += ["", "¶ 3 — Cardinality", "", "cardinality: # reference fields whose member count is constrained"]
    for dialect in AUTHORED:
        path = schemas / f"{dialect}.schema.json"
        if not path.is_file():
            continue
        schema = json.loads(path.read_text(encoding="utf-8"))
        collected = []
        for block in schema.get("accumulated_blocks", []):
            if block.get("min_items") is not None:
                collected.append(f"    {block['container']} min_items={block['min_items']}")
            for field in block.get("fields", []):
                references = field.get("references", {})
                if references.get("cardinality") not in (None, "zero_or_more"):
                    collected.append(
                        f"    {block['key']}.{field['name']} {references['cardinality']}"
                    )
        if collected:
            lines.append(f"  {dialect}:")
            lines.extend(sorted(set(collected)))
    return lines


# ── § 4 — ENTRY ──


def main() -> int:
    parser = argparse.ArgumentParser(description="regenerate the shared TDSL lock and contracts")
    parser.add_argument("--kernel", default=str(DEFAULT_KERNEL), help="path to the kernel grammar repo")
    parser.add_argument("--out", default=str(SHARED), help="output directory")
    args = parser.parse_args()

    schemas = Path(args.kernel).expanduser() / SCHEMA_SUBPATH
    if not (schemas / "registry.json").is_file():
        print(f"FAIL: no schema registry under {schemas}", file=sys.stderr)
        return 2

    out = Path(args.out).expanduser()
    emit(out / "schema-lock.tdsl", build_lock(schemas))
    emit(out / "field-contracts.tdsl", build_contracts(schemas))
    return 0


if __name__ == "__main__":
    sys.exit(main())
